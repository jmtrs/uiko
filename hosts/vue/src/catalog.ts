import { defineCatalog } from "@json-render/core";
import { defineRegistry, useStateStore } from "@json-render/vue";
import { schema } from "@json-render/vue/schema";
import { h } from "vue";
import { z } from "zod";

import { resolveRowBinding } from "./json-render-adapter";

const scalarSchema = z.union([
  z.string(),
  z.number(),
  z.boolean(),
  z.null(),
]);

export const catalog = defineCatalog(schema, {
  components: {
    Stack: {
      props: z.object({
        uikoId: z.string(),
      }),
      description: "Vertical container generated by the uiko renderer adapter.",
    },
    Text: {
      props: z.object({
        uikoId: z.string(),
        value: z.string(),
      }),
      description: "Plain text. Upstream text is never interpreted as markup.",
    },
    Field: {
      props: z.object({
        uikoId: z.string(),
        label: z.string(),
        binding: z.string(),
        value: z.unknown(),
      }),
      description: "Label plus a value resolved from a compiled logical query.",
    },
    Table: {
      props: z.object({
        uikoId: z.string(),
        binding: z.string(),
        rows: z.array(z.unknown()),
        columns: z.array(
          z.object({
            label: z.string(),
            binding: z.string(),
          }),
        ),
      }),
      description: "Table over a compiled list binding with optional explicit columns.",
    },
    Select: {
      props: z.object({
        uikoId: z.string(),
        label: z.string(),
        value: scalarSchema,
        options: z.array(
          z.object({
            label: z.string(),
            value: scalarSchema,
          }),
        ),
      }),
      description: "Select bound to one declared page-local state key.",
    },
    Pagination: {
      props: z.object({
        uikoId: z.string(),
        pageValue: z.number(),
        page: z.unknown(),
        pageSize: z.unknown(),
        total: z.unknown(),
      }),
      description: "Previous/Next controls over compiled page metadata.",
    },
  },
  actions: {},
});

export const { registry } = defineRegistry(catalog, {
  components: {
    Stack: ({ props, children }) =>
      h(
        "section",
        {
          "data-uiko-id": props.uikoId,
          "data-uiko-kind": "Stack",
        },
        children,
      ),
    Text: ({ props }) =>
      h(
        "p",
        {
          "data-uiko-id": props.uikoId,
          "data-uiko-kind": "Text",
        },
        props.value,
      ),
    Field: ({ props }) =>
      h(
        "div",
        {
          "data-uiko-id": props.uikoId,
          "data-uiko-kind": "Field",
          "data-uiko-binding": props.binding,
        },
        [
          h("strong", null, props.label),
          h("span", { "aria-live": "polite" }, formatValue(props.value)),
        ],
      ),
    Table: ({ props }) =>
      renderTable(
        props.uikoId,
        props.binding,
        props.rows,
        props.columns,
      ),
    Select: ({ props, bindings }) => {
      const { set } = useStateStore();
      const selectedIndex = props.options.findIndex((option) =>
        Object.is(option.value, props.value),
      );

      return h("label", { "data-uiko-id": props.uikoId }, [
        h("span", null, props.label),
        h(
          "select",
          {
            "data-uiko-kind": "Select",
            value: String(selectedIndex < 0 ? 0 : selectedIndex),
            onChange: (event: Event) => {
              const element = event.currentTarget;
              if (!(element instanceof HTMLSelectElement)) {
                return;
              }
              const option = props.options[element.selectedIndex];
              const path = bindings?.value;
              if (option !== undefined && path !== undefined) {
                set(path, option.value);
              }
            },
          },
          props.options.map((option, index) =>
            h(
              "option",
              {
                value: String(index),
                selected: index === selectedIndex,
              },
              option.label,
            ),
          ),
        ),
      ]);
    },
    Pagination: ({ props, bindings }) => {
      const { set } = useStateStore();
      const currentPage = numericValue(props.pageValue);
      const responsePage = numericValue(props.page);
      const pageSize = numericValue(props.pageSize);
      const total = numericValue(props.total);
      const pagePath = bindings?.pageValue;
      const effectivePage = responsePage ?? currentPage ?? 1;
      const previousDisabled = effectivePage <= 1;
      const nextDisabled =
        pageSize === null || total === null
          ? true
          : effectivePage * pageSize >= total;

      const setPage = (nextPage: number): void => {
        if (pagePath !== undefined) {
          set(pagePath, nextPage);
        }
      };

      return h(
        "nav",
        {
          "data-uiko-id": props.uikoId,
          "data-uiko-kind": "Pagination",
          "aria-label": "Pagination",
        },
        [
          h(
            "button",
            {
              type: "button",
              disabled: previousDisabled,
              onClick: () => setPage(Math.max(1, effectivePage - 1)),
            },
            "Previous",
          ),
          h("span", { "aria-live": "polite" }, `Page ${effectivePage}`),
          h(
            "button",
            {
              type: "button",
              disabled: nextDisabled,
              onClick: () => setPage(effectivePage + 1),
            },
            "Next",
          ),
        ],
      );
    },
  },
});

interface TableColumn {
  label: string;
  binding: string;
}

function renderTable(
  uikoId: string,
  binding: string,
  rows: unknown[],
  declaredColumns: TableColumn[],
): ReturnType<typeof h> {
  const records = rows.filter(isRecord);
  const columns =
    declaredColumns.length > 0
      ? declaredColumns
      : Array.from(
          new Set(records.flatMap((row) => Object.keys(row))),
        ).map((column) => ({ label: column, binding: column }));

  return h(
    "table",
    {
      "data-uiko-id": uikoId,
      "data-uiko-kind": "Table",
      "data-uiko-binding": binding,
      "aria-label": binding,
    },
    [
      h(
        "thead",
        null,
        h(
          "tr",
          null,
          columns.map((column) => h("th", { scope: "col" }, column.label)),
        ),
      ),
      h(
        "tbody",
        null,
        records.map((row) =>
          h(
            "tr",
            null,
            columns.map((column) =>
              h("td", null, formatValue(resolveRowBinding(row, column.binding))),
            ),
          ),
        ),
      ),
    ],
  );
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function numericValue(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function formatValue(value: unknown): string {
  if (value === null || value === undefined) {
    return "";
  }
  if (typeof value === "string") {
    return value;
  }
  if (
    typeof value === "number" ||
    typeof value === "boolean" ||
    typeof value === "bigint"
  ) {
    return String(value);
  }
  return JSON.stringify(value);
}
